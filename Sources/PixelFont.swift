    /// Render a string into one texture (1px spacing between glyphs).
    static func texture(_ text: String, color: NSColor) -> SKTexture {
        let chars = Array(text.uppercased())
        let w = max(1, chars.count * (glyphW + 1) - 1)
        let h = glyphH
        let c = color.usingColorSpace(.deviceRGB) ?? color
        let r = UInt8(c.redComponent * 255)
        let g = UInt8(c.greenComponent * 255)
        let b = UInt8(c.blueComponent * 255)

        var data = [UInt8](repeating: 0, count: w * h * 4)
        for (ci, ch) in chars.enumerated() {
            guard let glyph = glyphs[ch] else { continue }
            let x0 = ci * (glyphW + 1)
            for (y, row) in glyph.enumerated() {
                for (x, px) in Array(row).enumerated() where px == "#" {
                    let i = (y * w + x0 + x) * 4
                    data[i] = r; data[i + 1] = g; data[i + 2] = b; data[i + 3] = 255
                }
            }
        }
        return Pixel.textureFromRGBA(&data, width: w, height: h)
    }
}

/// A sprite node displaying bitmap-font text; set `text` to re-render.
final class BitmapLabel: SKSpriteNode {
    var textColor: NSColor
    var text: String {
        didSet { render() }
    }

    /// anchorX: 0 = left-aligned, 0.5 = centered, 1 = right-aligned
    init(_ text: String, color: NSColor = Palette.white, anchorX: CGFloat = 0) {
        self.text = text
        self.textColor = color
        super.init(texture: nil, color: .clear, size: .zero)
        anchorPoint = CGPoint(x: anchorX, y: 0)
        render()
    }

    required init?(coder: NSCoder) { fatalError() }

    private func render() {
        let tex = PixelFont.texture(text, color: textColor)
        texture = tex
        size = tex.size()
    }
}
